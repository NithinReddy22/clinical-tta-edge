"""
baseline/dataset_setup.py
==========================
Instructions and helper code for setting up the domain-shift datasets
used in clinical-tta-edge Phase 1.

NO private or IRB-restricted data is used.
All datasets listed here are publicly available.

Datasets:
---------
1. COCO 2017 val (source domain validation)
   URL: https://cocodataset.org/#download
   License: CC BY 4.0

2. MOT17 (target domain 1 — indoor surveillance)
   URL: https://motchallenge.net/data/MOT17/
   License: Creative Commons Attribution-NonCommercial-ShareAlike 3.0
   Note: Download the detection results separately; use ground-truth annotations.

3. HDA Person Dataset (target domain 2 — hospital corridors)
   URL: http://vislab.isr.ist.utl.pt/hda-dataset/
   License: Free for academic use
   Note: Contains annotated pedestrian sequences from hospital camera feeds.
   If HDA is unavailable, use ShanghaiTech Campus as an indoor person detection proxy.

4. Synthetic shift (target domain 3 — controlled)
   Generated in-script by applying brightness/contrast perturbations to COCO val.
   No external download needed.
"""

import os
import urllib.request
import shutil
import zipfile
from pathlib import Path


# ---------------------------------------------------------------------------
# Dataset paths (configure these)
# ---------------------------------------------------------------------------
DATASET_ROOT = os.environ.get("DATASET_ROOT", "./data")
COCO_VAL_DIR = os.path.join(DATASET_ROOT, "coco", "images", "val2017")
MOT17_DIR = os.path.join(DATASET_ROOT, "mot17")
HDA_DIR = os.path.join(DATASET_ROOT, "hda")


def check_coco_val():
    """Check if COCO 2017 val images are present."""
    if os.path.isdir(COCO_VAL_DIR):
        n = len(list(Path(COCO_VAL_DIR).glob("*.jpg")))
        print(f"[OK] COCO val: {n} images found at {COCO_VAL_DIR}")
        return True
    else:
        print(f"[MISSING] COCO val not found at {COCO_VAL_DIR}")
        print(
            "Download instructions:\n"
            "  wget http://images.cocodataset.org/zips/val2017.zip\n"
            "  wget http://images.cocodataset.org/annotations/annotations_trainval2017.zip\n"
            "  Unzip both into ./data/coco/\n"
            "  Then create a data.yaml pointing to ./data/coco/"
        )
        return False


def check_mot17():
    """Check if MOT17 sequences are present."""
    if os.path.isdir(MOT17_DIR):
        seqs = [d for d in os.listdir(MOT17_DIR) if os.path.isdir(os.path.join(MOT17_DIR, d))]
        print(f"[OK] MOT17: {len(seqs)} sequences found at {MOT17_DIR}")
        return True
    else:
        print(f"[MISSING] MOT17 not found at {MOT17_DIR}")
        print(
            "Download instructions:\n"
            "  Register at https://motchallenge.net/\n"
            "  Download MOT17Det.zip and extract to ./data/mot17/\n"
            "  Use convert_mot17_to_coco.py to generate COCO-format annotations"
        )
        return False


def make_coco_yaml(output_path: str = "experiments/configs/coco_val.yaml"):
    """Generate a data.yaml for COCO val evaluation."""
    os.makedirs(os.path.dirname(output_path), exist_ok=True)
    content = f"""# COCO 2017 Val — Baseline source-domain evaluation
path: {os.path.abspath(DATASET_ROOT)}/coco
train: images/train2017
val: images/val2017
nc: 80
names:
  0: person
  1: bicycle
  2: car
  # ... (full COCO class list)
"""
    with open(output_path, "w") as f:
        f.write(content)
    print(f"[OK] COCO val yaml written to {output_path}")
    return output_path


def make_synthetic_shift_yaml(shift_type: str = "brightness",
                               shift_value: float = -50.0,
                               output_path: str = "experiments/configs/coco_brightness_shift.yaml"):
    """
    Generate a data.yaml pointing to a brightness-shifted copy of COCO val.
    The shifted images are generated by apply_synthetic_shift().
    """
    shift_dir = os.path.join(DATASET_ROOT, f"coco_synthetic_{shift_type}")
    content = f"""# Synthetic shifted COCO val — {shift_type} shift = {shift_value}
path: {os.path.abspath(shift_dir)}
val: images
nc: 80
names:
  0: person
"""
    os.makedirs(os.path.dirname(output_path), exist_ok=True)
    with open(output_path, "w") as f:
        f.write(content)
    print(f"[OK] Synthetic shift yaml written to {output_path}")
    return output_path


def apply_synthetic_shift(shift_type: str = "brightness",
                           shift_value: float = -50.0,
                           max_images: int = 500):
    """
    Apply a controlled perturbation to COCO val images to create a synthetic
    target domain. This provides a quantified, reproducible domain shift.

    Args:
        shift_type:  "brightness" or "contrast"
        shift_value: Value to add (brightness) or scale factor (contrast)
        max_images:  Number of images to process
    """
    try:
        import cv2
        import numpy as np
    except ImportError:
        print("Install opencv-python: pip install opencv-python")
        return

    out_dir = os.path.join(DATASET_ROOT, f"coco_synthetic_{shift_type}", "images")
    os.makedirs(out_dir, exist_ok=True)

    src_images = sorted(Path(COCO_VAL_DIR).glob("*.jpg"))[:max_images]
    print(f"Applying {shift_type} shift ({shift_value}) to {len(src_images)} images...")

    for img_path in src_images:
        img = cv2.imread(str(img_path))
        if img is None:
            continue
        if shift_type == "brightness":
            shifted = np.clip(img.astype(np.int32) + shift_value, 0, 255).astype(np.uint8)
        elif shift_type == "contrast":
            shifted = np.clip(img.astype(np.float32) * shift_value, 0, 255).astype(np.uint8)
        else:
            shifted = img
        out_path = os.path.join(out_dir, img_path.name)
        cv2.imwrite(out_path, shifted)

    print(f"[OK] Synthetic shifted images written to {out_dir}")
    return out_dir


if __name__ == "__main__":
    print("clinical-tta-edge | Dataset Setup Check")
    print("=" * 50)
    check_coco_val()
    check_mot17()
    make_coco_yaml()
    print("\nRun apply_synthetic_shift() to generate a controlled domain shift.")
